#!/usr/bin/env python3
"""Generate the CF RAT constant blob: effects/common/rat_blob.h (PC bench copy)
and effects/ratx/blob.bin (the pedal's manifest const_blob).

Layout (float32, 2048 words = 8 KB, under the 16 KB L1D cache):
  [0, 1024)     rat_dtab  : 1N914 shunt pair (Rs 68, Is 2.52 nA, nVt 45.3 mV)
                            vo(u) for u = 0..4 V, 1024 points (exact solve)
  [1024, 1280)  rat_g_fb  : tan(pi fc100 / fs) per Distortion 0..10 (256 points)
  [1280, 1536)  rat_g_opa : tan(pi effBW / fs), same Distortion grid
  [1536, 1792)  rat_Rf    : Rf in ohms, same Distortion grid
  [1792, 2048)  rat_g_tone: tan(pi cutoff / fs) per Filter 0..1 (256 points)
fs = 8 x 44.1 kHz. Formulas as in tests/host/rat_accuracy.cpp reference().
Merged from Gemini's gen_dtab.py / gen_coeffs.py (2026-10-06).
"""
import math
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
FS = 8 * 44100.0


def shunt(u):
    K, nVt = 68.0 * 2.0 * 2.52e-9, 0.0453
    au = abs(u)
    v = min(au, 1.0)
    for _ in range(80):
        g = v + K * math.sinh(v / nVt) - au
        gp = 1.0 + (K / nVt) * math.cosh(v / nVt)
        step = max(-4 * nVt, min(4 * nVt, g / gp))
        v = max(0.0, min(au, v - step))
        if abs(step) < 1e-14:
            break
    return v


def dist_row(d):
    gtop = 10.0 ** (d * 0.3325)                  # 66.5 dB over 0..10
    rf = 47.0 * (gtop - 1.0)
    effbw = max(400.0, min(1.0e6 / max(gtop, 1.0), 20000.0))
    fc100 = min(1.0 / (2 * math.pi * rf * 100e-12), 0.45 * FS) if rf > 100.0 else 0.45 * FS
    return math.tan(math.pi * fc100 / FS), math.tan(math.pi * effbw / FS), rf


def main():
    dtab = [shunt(u) for u in np.linspace(0.0, 4.0, 1024)]
    rows = [dist_row(d) for d in np.linspace(0.0, 10.0, 256)]
    tone = [math.tan(math.pi * 475.0 * (min(32000.0, 0.45 * FS) / 475.0) ** f / FS)
            for f in np.linspace(0.0, 1.0, 256)]
    blob = np.array(dtab + [r[0] for r in rows] + [r[1] for r in rows]
                    + [r[2] for r in rows] + tone, dtype="<f4")
    assert blob.size == 2048
    blob.tofile(ROOT / "effects/ratx/blob.bin")
    body = ",\n".join("    " + ", ".join("%.9ef" % v for v in blob[i:i + 8])
                      for i in range(0, blob.size, 8))
    (ROOT / "effects/common/rat_blob.h").write_text(
        "/* rat_blob.h - GENERATED by tools/gen_rat_blob.py; do not edit.\n"
        " * The CF RAT constant blob (2048 floats). On the pedal the data comes\n"
        " * from the manifest const_blob (effects/ratx/blob.bin). */\n"
        "#ifndef RAT_BLOB_H\n#define RAT_BLOB_H\n\n"
        "#define RAT_BLOB_WORDS 2048\n"
        "#define RAT_DTAB_N     1024\n"
        "#define RAT_DTAB_UMAX  4.0f\n"
        "#define RAT_DTAB_SCALE 255.75f\n"
        "#define RAT_PTAB_N     256\n\n"
        "#if defined(__TI_COMPILER_VERSION__)\n"
        "extern const float rat_blob[];\n#else\n"
        "static const float rat_blob[2048] = {\n" + body + "\n};\n#endif\n\n"
        "#define rat_dtab   (rat_blob + 0)\n"
        "#define rat_g_fb   (rat_blob + 1024)\n"
        "#define rat_g_opa  (rat_blob + 1280)\n"
        "#define rat_Rf     (rat_blob + 1536)\n"
        "#define rat_g_tone (rat_blob + 1792)\n\n#endif\n")
    print("wrote effects/ratx/blob.bin and effects/common/rat_blob.h")


if __name__ == "__main__":
    main()
