// Generates the DR103 constant blob: effects/common/hw_blob.h (host array +
// offsets) and effects/{hiwatt,dr103diag}/blob.bin (the manifests' const_blob).
//   [0, 1024)      tanh on [0, 9], 256 cubic Hermite segments [p0 m0 a2 a3]
//   V1 net         101 knob positions x MNA_SS_SIZE(2, 1)  (Volume 0..100)
//   back half      101 knob positions x MNA_SS_SIZE(5, 2)  (Presence 0..100)
// The G1 knobs only take the 101 values 0..100, so the network tables are
// exact at every knob position (the pedal interpolates only while a knob is
// smoothed). They are derived with the same float mna_derive the DSP runs.
// Build + run: tools/gen_hiwatt_blob.bat
#include <cmath>
#include <cstdio>
#include <vector>
extern "C" {
#include "../effects/common/hiwatt_nets.h"
}

int main(int argc, char** argv)
{
    const char* root = argc > 1 ? argv[1] : ".";
    const int N = 256, KN = 101, V1SZ = MNA_SS_SIZE(2, 1), BHSZ = MNA_SS_SIZE(5, 2);
    const double XMAX = 9.0, FS = 176400.0;
    std::vector<float> blob;
    const double h = XMAX / N;
    for (int i = 0; i < N; ++i) {
        double x0 = i * h, x1 = x0 + h, p0 = std::tanh(x0), p1 = std::tanh(x1);
        double m0 = h * (1 - p0 * p0), m1 = h * (1 - p1 * p1);
        blob.push_back((float)p0); blob.push_back((float)m0);
        blob.push_back((float)(3 * (p1 - p0) - 2 * m0 - m1));
        blob.push_back((float)(2 * (p0 - p1) + m0 + m1));
    }
    const size_t offV1 = blob.size();
    for (int q = 0; q < KN; ++q) {
        MnaNet n; float w[MNA_MAXN], p[64];
        hw_v1net(&n, w, q / 100.0f);
        mna_derive(&n, w, (float)FS, p);
        blob.insert(blob.end(), p, p + V1SZ);
    }
    const size_t offBH = blob.size();
    for (int q = 0; q < KN; ++q) {
        MnaNet n; float w[MNA_MAXN], p[64];
        hw_backhalf(&n, w, q / 100.0f);
        mna_derive(&n, w, (float)FS, p);
        blob.insert(blob.end(), p, p + BHSZ);
    }
    for (const char* d : {"hiwatt", "dr103diag"}) {
        char path[512];
        std::snprintf(path, sizeof path, "%s/effects/%s/blob.bin", root, d);
        FILE* f = std::fopen(path, "wb");
        std::fwrite(blob.data(), 4, blob.size(), f);
        std::fclose(f);
    }
    char path[512];
    std::snprintf(path, sizeof path, "%s/effects/common/hw_blob.h", root);
    FILE* f = std::fopen(path, "w");
    std::fprintf(f,
        "/* hw_blob.h - GENERATED by tools/gen_hiwatt_blob.cpp; do not edit.\n"
        " * The DR103 constant blob (%zu floats): tanh table, then the V1 network\n"
        " * and the back half derived at every knob position 0..100 (the G1 knobs'\n"
        " * only values), packed as mna_ss.h systems. On the pedal the data comes\n"
        " * from the manifest const_blob (blob.bin). */\n"
        "#ifndef HW_BLOB_H\n#define HW_BLOB_H\n\n"
        "#define HW_TANH_N    %d\n#define HW_TANH_XMAX %.1ff\n"
        "#define HW_BLOB_V1   %zu   /* + knob * MNA_SS_SIZE(2, 1) */\n"
        "#define HW_BLOB_BH   %zu   /* + knob * MNA_SS_SIZE(5, 2) */\n"
        "#define HW_BLOB_WORDS %zu\n\n"
        "#if defined(__TI_COMPILER_VERSION__)\nextern const float hw_blob[];\n#else\n"
        "static const float hw_blob[%zu] = {\n",
        blob.size(), N, XMAX, offV1, offBH, blob.size(), blob.size());
    for (size_t i = 0; i < blob.size(); ++i)
        std::fprintf(f, "%s%.9ef%s", i % 4 == 0 ? "    " : "", blob[i], i + 1 == blob.size() ? "\n" : (i % 4 == 3 ? ",\n" : ", "));
    std::fprintf(f, "};\n#endif\n#define hw_tanhtab hw_blob\n\n#endif /* HW_BLOB_H */\n");
    std::fclose(f);
    std::printf("blob: %zu floats (%zu B), V1 at %zu, back half at %zu\n",
                blob.size(), blob.size() * 4, offV1, offBH);
    return 0;
}
