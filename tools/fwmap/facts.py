"""Per-function fact sheets for the firmware map, split into chunks.

    python tools/fwmap/facts.py [--per 150]

Needs build/fw/map/coverage.tsv and subsystems.tsv (run coverage.py and
subsystems.py first). For every function: size, reaching roots, callers,
callees, strings, MMIO bases, B14 globals, code-pointer locations and recon
mentions. Names given in the recon/map/*.md tables are shown next to
addresses. Writes build/fw/map/facts/chunk_NN.md and prints the chunk list.
"""
import argparse
import bisect
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
import coverage  # noqa: E402

ROW = re.compile(r"^\|\s*`?([0-9a-f]{8})`?\s*\|\s*`?([A-Za-z_][\w.$]*)`?\s*\|")


def load_names():
    """Names from the helpers' tables in recon/map/*.md:
    | addr | name | role | confidence | evidence |"""
    names = {}
    for md in sorted((ROOT / "recon/map").glob("*.md")):
        for line in open(md, encoding="utf-8", errors="replace"):
            m = ROW.match(line)
            if m and m[2] not in ("name", "unknown"):
                names[int(m[1], 16)] = m[2]
    return names


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--per", type=int, default=150)
    a = ap.parse_args()

    sub = {}
    for line in open(ROOT / "build/fw/map/subsystems.tsv", encoding="utf-8"):
        if line.startswith("addr"):
            continue
        f = line.rstrip("\n").split("\t")
        sub[int(f[0], 16)] = {"size": int(f[1]), "recon": f[2], "roots": f[3]}
    starts = sorted(sub)
    names = load_names()
    strs = coverage.strings_by_addr()
    _, words, calls, stubs = coverage.load(str(ROOT / "build/fw/map/main.dis"))

    def owner(x):
        i = bisect.bisect_right(starts, x) - 1
        return starts[i] if i >= 0 else None

    def nm(x):
        return "%08x%s" % (x, ("=" + names[x]) if x in names else "")

    callees, callers = defaultdict(set), defaultdict(set)
    for tgt, srcs in calls.items():
        t = stubs.get(tgt, tgt)
        if t not in sub:
            continue
        for s, _ in srcs:
            o = owner(s)
            if o is not None and o != t:
                callees[o].add(t)
                callers[t].add(o)
    ptr_at = defaultdict(list)
    for at, v in words:
        v = stubs.get(v, v)
        if v in sub:
            ptr_at[v].append(at)

    mmio, glob, fstr = defaultdict(set), defaultdict(set), defaultdict(set)
    last = {}
    for line in open(ROOT / "build/fw/map/main.dis", encoding="utf-8", errors="replace"):
        m = coverage.INS.match(line)
        if not m:
            continue
        addr = int(m[1], 16)
        o = owner(addr)
        if o is None:
            continue
        g = re.search(r"\*\+?B14\[(\d+)\]", m[6])
        if g:
            glob[o].add(int(g[1]))
        mk = re.match(r"(-?0x[0-9a-f]+|-?\d+),([AB]\d+)$", m[6].strip())
        if mk and m[5].startswith("MVK") and not m[5].startswith("MVKH"):
            last[mk[2]] = int(mk[1], 0) & 0xffff
        elif mk and m[5].startswith("MVKH"):
            v = (int(mk[1], 0) & 0xffff0000) | last.get(mk[2], 0)
            if v in strs:
                fstr[o].add(strs[v][:28])
            elif 0x01800000 <= v < 0x02000000:
                mmio[o].add(v & 0xfffff000)

    outdir = ROOT / "build/fw/map/facts"
    outdir.mkdir(parents=True, exist_ok=True)
    chunks = [starts[i:i + a.per] for i in range(0, len(starts), a.per)]
    for n, ch in enumerate(chunks):
        lo, hi = ch[0], ch[-1] + sub[ch[-1]]["size"]
        with open(outdir / ("chunk_%02d.md" % n), "w", encoding="utf-8") as f:
            f.write("# Fact sheet chunk %02d: %08x..%08x (%d functions)\n\n" % (n, lo, hi, len(ch)))
            f.write("Generated by tools/fwmap/facts.py. Callers/callees are direct calls only; "
                    "ptr@ lists data words holding the function's address (tables/callbacks).\n\n")
            for x in ch:
                s = sub[x]
                f.write("## %s  size %d\n" % (nm(x), s["size"]))
                if s["roots"]:
                    f.write("- roots: %s\n" % s["roots"])
                cl = sorted(callers[x])
                if cl:
                    f.write("- callers (%d): %s\n" % (len(cl), " ".join(nm(c) for c in cl[:12])
                                                       + (" ..." if len(cl) > 12 else "")))
                ce = sorted(callees[x])
                if ce:
                    f.write("- calls (%d): %s\n" % (len(ce), " ".join(nm(c) for c in ce[:16])
                                                     + (" ..." if len(ce) > 16 else "")))
                if ptr_at[x]:
                    f.write("- ptr@: %s\n" % " ".join("%08x" % p for p in ptr_at[x][:8]))
                if fstr[x]:
                    f.write("- strings: %s\n" % " | ".join(sorted(fstr[x])[:10]))
                if mmio[x]:
                    f.write("- mmio: %s\n" % " ".join("%08x" % m for m in sorted(mmio[x])))
                if glob[x]:
                    f.write("- B14 globals: %s\n" % " ".join(str(g) for g in sorted(glob[x])[:12]))
                if s["recon"]:
                    f.write("- recon: %s\n" % s["recon"])
                f.write("\n")
        print("chunk_%02d  %08x..%08x  %3d fn  %6d B  roots: %s" % (
            n, lo, hi, len(ch), sum(sub[x]["size"] for x in ch),
            ",".join(sorted({r for x in ch for r in sub[x]["roots"].split(",") if r}))[:90]))


if __name__ == "__main__":
    main()
