"""Generate compact 2093-word muff_blob for multi-slot rigs (cfm_pre and cfmaster).

Preserves the first 1928 floats (clip1, clip2, tanh, sus_g) bit-identically.
Decimates the 645-float tone table (129 entries x 5 floats) down to 33 entries x 5 floats
by sub-sampling every 4th point across the 0..1 range (saving 480 floats = 1920 bytes).
"""
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# 1. Read original 2573-word blob
full_data = (ROOT / "effects" / "muffx" / "blob.bin").read_bytes()
assert len(full_data) == 2573 * 4, f"Expected 10292 bytes, got {len(full_data)}"
floats = list(struct.unpack("<2573f", full_data))

prefix = floats[:1928]
tone = floats[1928:]
assert len(tone) == 129 * 5

# Decimate tone: 33 points (0, 4, 8, ..., 128)
decimated_tone = []
for i in range(33):
    entry_idx = i * 4
    decimated_tone.extend(tone[entry_idx * 5 : (entry_idx + 1) * 5])

assert len(decimated_tone) == 33 * 5 == 165
compact_floats = prefix + decimated_tone
assert len(compact_floats) == 2093

compact_bytes = struct.pack(f"<{len(compact_floats)}f", *compact_floats)
assert len(compact_bytes) == 2093 * 4 == 8372

# 2. Write blob.bin to cfm_pre and cfmaster
(ROOT / "effects" / "cfm_pre" / "blob.bin").write_bytes(compact_bytes)
print(f"Wrote {len(compact_bytes)} B to effects/cfm_pre/blob.bin")

(ROOT / "effects" / "cfmaster" / "blob.bin").write_bytes(compact_bytes)
print(f"Wrote {len(compact_bytes)} B to effects/cfmaster/blob.bin")

# 3. Read constants from original muff_blob.h
orig_h = (ROOT / "effects" / "common" / "muff_blob.h").read_text(encoding="utf-8")
clip_consts = orig_h[orig_h.find("#define MUFF_CLIP1_MAX") : orig_h.find("#if defined(__TI_COMPILER_VERSION__)")]

# 4. Generate compact C array for muff_blob_compact.h
with open(ROOT / "effects" / "common" / "muff_blob_compact.h", "w") as f:
    f.write("/* muff_blob_compact.h - GENERATED by tools/gen_compact_muff_blob.py; do not edit. */\n")
    f.write("#ifndef MUFF_BLOB_COMPACT_H\n#define MUFF_BLOB_COMPACT_H\n\n")
    f.write("#define MUFF_BLOB_WORDS 2093\n")
    f.write("#define MUFF_CLIP1_TAB (muff_blob + 0)\n")
    f.write("#define MUFF_CLIP2_TAB (muff_blob + 771)\n")
    f.write("#define MUFF_TANH_TAB (muff_blob + 1542)\n")
    f.write("#define MUFF_SUS_G (muff_blob + 1799)\n")
    f.write("#define MUFF_TONE (muff_blob + 1928)\n\n")
    f.write(clip_consts)
    f.write("#if defined(__TI_COMPILER_VERSION__)\n")
    f.write("extern const float muff_blob[];\n")
    f.write("#else\n")
    f.write("static const float muff_blob[2093] = {\n")
    for i in range(0, len(compact_floats), 8):
        chunk = compact_floats[i : i + 8]
        f.write("    " + ", ".join(f"{x:.9e}f" for x in chunk) + ",\n")
    f.write("};\n#endif\n\n#endif /* MUFF_BLOB_COMPACT_H */\n")

print("Generated effects/common/muff_blob_compact.h successfully")
