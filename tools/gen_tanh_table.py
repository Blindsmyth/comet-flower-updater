"""Generate the Hiwatt tanh table (effects/common/hw_tanhtab.h + effects/hiwatt/tanh.bin).

tanh on [0, 9] as 256 cubic Hermite segments (value + slope 1 - tanh^2 at the
knots), rows [p0 m0 a2 a3] for p0 + f (m0 + f (a2 + f a3)), f in [0, 1).
Max error 3.9e-8 (float resolution). On the pedal the floats come from the
DR103 manifest's const_blob (stomphacks emits it after the param table).

    python tools/gen_tanh_table.py
"""
from pathlib import Path

import numpy as np

N, XMAX, SYMBOL = 256, 9.0, "hw_tanhtab"
root = Path(__file__).resolve().parents[1]
x = np.linspace(0, XMAX, N + 1)
h = x[1] - x[0]
y = np.tanh(x)
d = 1 - y * y
p0, p1, m0, m1 = y[:-1], y[1:], h * d[:-1], h * d[1:]
tab = np.stack([p0, m0, 3 * (p1 - p0) - 2 * m0 - m1, 2 * (p0 - p1) + m0 + m1], 1).astype("<f4")
flat = tab.reshape(-1)
for d in ("hiwatt", "dr103diag"):
    (root / f"effects/{d}/tanh.bin").write_bytes(flat.tobytes())
vals = ",\n".join("    " + ", ".join(f"{v:.9e}f" for v in flat[i:i + 4]) for i in range(0, flat.size, 4))
(root / "effects/common/hw_tanhtab.h").write_text(f"""\
/* hw_tanhtab.h - GENERATED by tools/gen_tanh_table.py; do not edit.
 * tanh on [0, {XMAX:g}] as {N} cubic Hermite segments, rows [p0 m0 a2 a3].
 * On the pedal the data comes from the DR103 manifest const_blob ({flat.size} words).
 */
#ifndef HW_TANHTAB_H
#define HW_TANHTAB_H

#define HW_TANH_N    {N}
#define HW_TANH_XMAX {XMAX:.1f}f

#if defined(__TI_COMPILER_VERSION__)
extern const float {SYMBOL}[];
#else
static const float {SYMBOL}[{flat.size}] = {{
{vals}
}};
#endif

#endif /* HW_TANHTAB_H */
""", newline="\n")
print(f"{N} segments, {flat.size} floats")
