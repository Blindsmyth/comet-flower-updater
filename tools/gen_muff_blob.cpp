#define private public
#include "ADAAWaveshaper.h"
#include "ToneStackMath.h"
#include "MuffCircuit.h"
#undef private

#include <iostream>
#include <fstream>
#include <vector>
#include <cmath>
#include <algorithm>
#include <iomanip>

using namespace std;

int main() {
    double osRate = 44100.0 * 4.0;
    
    WaveshaperFunctions::DiodeCapFeedbackStage clip1;
    clip1.build(VioletSpecs::RF_Q2, VioletSpecs::CF, VioletSpecs::DIODE_IS, VioletSpecs::DIODE_NVT, 
                osRate, VioletSpecs::kInputMaxQ2, 256, VioletSpecs::kOpenLoopA, VioletSpecs::kRhoQ2);
                
    WaveshaperFunctions::DiodeCapFeedbackStage clip2;
    clip2.build(VioletSpecs::RF_Q3, VioletSpecs::CF, VioletSpecs::DIODE_IS, VioletSpecs::DIODE_NVT, 
                osRate, VioletSpecs::kInputMaxQ3, 256, VioletSpecs::kOpenLoopA, VioletSpecs::kRhoQ3);

    vector<float> blob;

    for (int i = 0; i <= 256; i++) {
        blob.push_back(clip1.tables->cells[i].v);
        blob.push_back(clip1.tables->cells[i].w);
        blob.push_back(clip1.tables->cells[i].V);
    }
    
    for (int i = 0; i <= 256; i++) {
        blob.push_back(clip2.tables->cells[i].v);
        blob.push_back(clip2.tables->cells[i].w);
        blob.push_back(clip2.tables->cells[i].V);
    }

    // tanh_tab: 257 points for domain 0..8.5
    for (int i = 0; i <= 256; i++) {
        float x = i * (8.5f / 256.0f);
        blob.push_back(std::tanh(x));
    }

    for (int i = 0; i <= 128; i++) {
        float s = i / 128.0f;
        float rThev = s * (1.0f - s) * 100.0e3f;
        float fHpQ2 = 1.0f / (6.2831853f * 0.1e-6f * (rThev + 29.0e3f));
        float g = std::tan(3.14159265358979323846 * fHpQ2 / osRate);
        blob.push_back(g);
    }

    for (int i = 0; i <= 128; i++) {
        float t = i / 128.0f;
        auto c = ToneStackMath::muffTone(VioletSpecs::R14, VioletSpecs::R15,
                                         VioletSpecs::C10, VioletSpecs::C11,
                                         VioletSpecs::R_POT, VioletSpecs::RL_Q4,
                                         t, osRate);
        blob.push_back(c.b0);
        blob.push_back(c.b1);
        blob.push_back(c.b2);
        blob.push_back(c.a1);
        blob.push_back(c.a2);
    }

    ofstream bin("effects/muffx/blob.bin", ios::binary);
    bin.write((char*)blob.data(), blob.size() * 4);
    bin.close();

    ofstream h("effects/common/muff_blob.h");
    h << "/* muff_blob.h - GENERATED by tools/gen_muff_blob.cpp; do not edit. */\n";
    h << "#ifndef MUFF_BLOB_H\n#define MUFF_BLOB_H\n\n";
    h << "#define MUFF_BLOB_WORDS " << blob.size() << "\n";
    h << "#define MUFF_CLIP1_TAB (muff_blob + 0)\n";
    h << "#define MUFF_CLIP2_TAB (muff_blob + 771)\n";
    h << "#define MUFF_TANH_TAB (muff_blob + 1542)\n";
    h << "#define MUFF_SUS_G (muff_blob + 1799)\n";
    h << "#define MUFF_TONE (muff_blob + 1928)\n\n";
    
    h << "#define MUFF_CLIP1_MAX " << clip1.tables->rhsMax << "f\n";
    h << "#define MUFF_CLIP1_DR  " << clip1.tables->dr << "f\n";
    h << "#define MUFF_CLIP1_INV_DR " << clip1.tables->invDr << "f\n";
    h << "#define MUFF_CLIP1_V_END " << clip1.tables->vEnd << "f\n";
    h << "#define MUFF_CLIP1_W_END " << clip1.tables->wEnd << "f\n";
    h << "#define MUFF_CLIP1_V_INT_END " << clip1.tables->VEnd << "f\n";
    h << "#define MUFF_CLIP1_DVDR_END " << clip1.tables->dvdrEnd << "f\n";
    h << "#define MUFF_CLIP1_DWDR_END " << clip1.tables->dwdrEnd << "f\n";
    h << "#define MUFF_CLIP1_C " << clip1.tables->c << "f\n";
    h << "#define MUFF_CLIP1_G " << clip1.tables->g << "f\n";

    h << "#define MUFF_CLIP2_MAX " << clip2.tables->rhsMax << "f\n";
    h << "#define MUFF_CLIP2_DR  " << clip2.tables->dr << "f\n";
    h << "#define MUFF_CLIP2_INV_DR " << clip2.tables->invDr << "f\n";
    h << "#define MUFF_CLIP2_V_END " << clip2.tables->vEnd << "f\n";
    h << "#define MUFF_CLIP2_W_END " << clip2.tables->wEnd << "f\n";
    h << "#define MUFF_CLIP2_V_INT_END " << clip2.tables->VEnd << "f\n";
    h << "#define MUFF_CLIP2_DVDR_END " << clip2.tables->dvdrEnd << "f\n";
    h << "#define MUFF_CLIP2_DWDR_END " << clip2.tables->dwdrEnd << "f\n";
    h << "#define MUFF_CLIP2_C " << clip2.tables->c << "f\n";
    h << "#define MUFF_CLIP2_G " << clip2.tables->g << "f\n";

    h << "#if defined(__TI_COMPILER_VERSION__)\n";
    h << "extern const float muff_blob[];\n";
    h << "#else\n";
    h << "static const float muff_blob[" << blob.size() << "] = {\n";
    h << std::scientific << std::setprecision(9);
    for (size_t i = 0; i < blob.size(); i += 8) {
        h << "    ";
        for (size_t j = i; j < min(blob.size(), i + 8); j++) {
            h << blob[j] << "f" << (j == blob.size() - 1 ? "" : ", ");
        }
        h << "\n";
    }
    h << "};\n#endif\n\n#endif\n";
    h.close();

    cout << "Generated blob size: " << blob.size() << " floats (" << (blob.size()*4) << " bytes)\n";
    return 0;
}
