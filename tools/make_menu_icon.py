"""Comet Flower settings-page icon for the SETTING chooser (24x32, 1 bit).

    python tools/make_menu_icon.py        # writes firmware/controller/menu_icon.h
                                          # and build/ui_mock/menu_icon.png

Format (verified on the stock OUTPUT/SETUP icons, descriptor words 1..3 =
c017ea88/c017e788/c017e488): 96 bytes, four 8-row pages of 24 columns, byte =
one column of 8 pixels, bit 0 on top; the chooser (c01579cc -> c011c508) draws
24x30 of it. Words 1, 2, 3 are the small, medium and large variants (the stock
icons keep the label the same size and grow the picture).
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
W, H = 24, 32

# 5x7 glyphs, rows top to bottom, bit 4 = left column
GLYPH = {
    "C": [0b01110, 0b10001, 0b10000, 0b10000, 0b10000, 0b10001, 0b01110],
    "F": [0b11111, 0b10000, 0b10000, 0b11110, 0b10000, 0b10000, 0b10000],
}


FLOWER = {
    "small": [
        "..#..#..",
        ".#.##.#.",
        "#..##..#",
        ".##..##.",
        ".##..##.",
        "#..##..#",
        ".#.##.#.",
        "..#..#..",
    ],
    "medium": [
        "....##....",
        "...#..#...",
        ".##.##.##.",
        "#..#..#..#",
        "#.#.##.#.#",
        ".##.##.##.",
        "#..#..#..#",
        "#..#..#..#",
        ".##.##.##.",
        "...#..#...",
        "....##....",
    ],
    "large": [
        ".....####.....",
        "....#....#....",
        "....#....#....",
        ".##..#..#..##.",
        "#..#.####.#..#",
        "#...##..##...#",
        ".#..#.##.#..#.",
        ".#..#.##.#..#.",
        "#...##..##...#",
        "#..#.####.#..#",
        ".##..#..#..##.",
        "....#....#....",
        "....#....#....",
        ".....####.....",
    ],
}


def icon(radius):
    px = [[0] * W for _ in range(H)]
    x0 = (W - 11) // 2                           # "CF": 5 + 1 + 5 columns
    for k, ch in enumerate("CF"):
        for r, bits in enumerate(GLYPH[ch]):
            for c in range(5):
                if bits >> (4 - c) & 1:
                    px[r][x0 + 6 * k + c] = 1
    # flower: hand-drawn pixel art per size, centred below the label
    art = FLOWER[radius]
    y0 = 9 + (H - 9 - len(art)) // 2
    x1 = (W - len(art[0])) // 2
    for r, row in enumerate(art):
        for c, ch in enumerate(row):
            if ch == "#":
                px[y0 + r][x1 + c] = 1
    return px


def pack(px):
    out = bytearray()
    for page in range(H // 8):
        for x in range(W):
            out.append(sum(px[page * 8 + r][x] << r for r in range(8)))
    return bytes(out)


VARIANTS = [("small", "small"), ("medium", "medium"), ("large", "large")]


def main():
    icons = [(name, pack(icon(r)), icon(r)) for name, r in VARIANTS]
    lines = ["/* Generated by tools/make_menu_icon.py: do not edit. */"]
    for name, data, _ in icons:
        lines.append("static const unsigned char menu_icon_%s[96] = {" % name)
        for i in range(0, 96, 12):
            lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 12]) + ",")
        lines.append("};")
    (ROOT / "firmware/controller/menu_icon.h").write_text("\n".join(lines) + "\n", newline="\n")
    try:
        from PIL import Image
    except ImportError:
        return
    out = Image.new("1", (3 * (W + 4) * 4, H * 4), 0)
    for k, (_, _, px) in enumerate(icons):
        im = Image.new("1", (W, H))
        for y in range(H):
            for x in range(W):
                im.putpixel((x, y), px[y][x])
        out.paste(im.resize((W * 4, H * 4)), (k * (W + 4) * 4, 0))
    (ROOT / "build/ui_mock").mkdir(parents=True, exist_ok=True)
    out.save(ROOT / "build/ui_mock/menu_icon.png")


if __name__ == "__main__":
    main()
