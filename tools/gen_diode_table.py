"""Generate the Green 808X diode-solve table (effects/common/ts808_dtab.h).

The clipping stage's implicit equation, normalised (u = v / nVt):

    c * u + sinh(u) = r,   c = nVt / (2 Is) * (1/Rf + gC4),   r = rhs / (2 Is Rf)

c depends only on the Drive knob (about 340..500); r is per sample. The table
holds u(c, |r|) as cubic Hermite segments on a pseudo-log r grid: K segments
per octave from 2^LO to 2^HI, so the segment index and the position t in it
come straight from the float bits of |r| (exponent + top mantissa bits).
Each segment stores u = p0 + t*(m0 + t*(a2 + t*a3)), solved in double.
NC rows span c; the kernel blends four neighbouring rows per sample with
cubic Lagrange weights fixed per block. Max error about 4e-6 V (table only).
Below 2^LO, u = r / (c + 1) (the diodes are off; error < 1e-7 V).

The same floats go to effects/drv808x/dtab.bin, which the manifest's
const_blob loads ("init"); stomphacks emits the blob last in .const, so the
param table stays first. The blob size there must equal the float count.

    python tools/gen_diode_table.py
"""
from pathlib import Path

import numpy as np

IS, NVT = 2.52e-9, 1.752 * 0.025852
LOG2K, LO, HI, NC = 3, 4, 28, 9
CMIN, CMAX = 315.0, 525.0        # c spans ~340..500; cubic needs a row of margin
K = 1 << LOG2K
NSEG = (HI - LO) * K
SYMBOL = "tsx_dtab"


def solve(c, r):
    r = np.asarray(r, float)
    u = np.where(np.abs(r) > c * 3, np.sign(r) * np.log(2 * np.abs(r) + 1), r / (c + 1))
    for _ in range(60):
        u = u - (c * u + np.sinh(u) - r) / (c + np.cosh(u))
    return u


def table():
    knots = np.array([2.0 ** e * (1 + m / K) for e in range(LO, HI) for m in range(K)] + [2.0 ** HI])
    h = np.diff(knots)
    rows = []
    for c in np.linspace(CMIN, CMAX, NC):
        u = solve(c, knots)
        d = 1 / (c + np.cosh(u))                         # du/dr
        p0, p1, m0, m1 = u[:-1], u[1:], h * d[:-1], h * d[1:]
        a2 = 3 * (p1 - p0) - 2 * m0 - m1
        a3 = 2 * (p0 - p1) + m0 + m1
        rows.append(np.stack([p0, m0, a2, a3], axis=1))
    return np.array(rows, dtype=np.float32)              # [NC][NSEG][4]


def main():
    t = table()
    flat = t.reshape(-1)
    root = Path(__file__).resolve().parents[1]
    vals = ",\n".join("    " + ", ".join(f"{v:.9g}f" for v in flat[i:i + 4]) for i in range(0, flat.size, 4))
    (root / "effects/common/ts808_dtab.h").write_text(f"""\
/* ts808_dtab.h - GENERATED by tools/gen_diode_table.py; do not edit.
 * Diode-pair solve table for ts808_exact.h: u(c, |r|) of c*u + sinh(u) = r,
 * cubic Hermite segments, [{NC} c rows][{NSEG} segments][p0 m0 a2 a3].
 * On the pedal the data comes from the manifest const_blob ({flat.size} words).
 */
#ifndef TS808_DTAB_H
#define TS808_DTAB_H

#define TSX_DT_LOG2K {LOG2K}
#define TSX_DT_LO    {LO}
#define TSX_DT_HI    {HI}
#define TSX_DT_NC    {NC}
#define TSX_DT_NSEG  {NSEG}
#define TSX_DT_CMIN  {CMIN}f
#define TSX_DT_CMAX  {CMAX}f

#if defined(__TI_COMPILER_VERSION__)
extern const float {SYMBOL}[];
#else
static const float {SYMBOL}[{flat.size}] = {{
{vals}
}};
#endif

#endif /* TS808_DTAB_H */
""", newline="\n")
    blob = root / "effects/drv808x/dtab.bin"
    blob.write_bytes(flat.astype("<f4").tobytes())
    print(f"{NC} rows x {NSEG} segments = {flat.size} floats ({flat.size * 4} B)")


if __name__ == "__main__":
    main()
